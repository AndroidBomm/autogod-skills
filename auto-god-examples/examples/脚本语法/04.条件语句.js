// if-else语句
var score = 85;
if (score >= 90) {
    console.log("优秀");
} else if (score >= 80) {
    console.log("良好"); // 输出: 良好
} else {
    console.log("及格");
}

// switch语句
var day = 3;
switch (day) {
    case 1:
        console.log("星期一");
        break;
    case 2:
        console.log("星期二");
        break;
    case 3:
        console.log("星期三"); // 输出: 星期三
        break;
    default:
        console.log("其他天");
}